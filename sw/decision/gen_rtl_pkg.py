"""Generate rtl/decision/dec_pkg.sv from the decision contract (bins, vocabulary, guard limits, rule thresholds,
transition table).  Run after any contract change:  python3 gen_rtl_pkg.py"""
import os

from contract import (ACTIONS, BOS, EDGES, I_BASE, I_INV, INV_PERSIST, LIM_I, LIM_T, LIM_V, MODE_BASE, MODES, ROOT,
                      RULE_I_OC, RULE_T_SAFE, RULE_V_RESTR, RULE_V_SAFE, T_BASE, T_INV, TT, V_BASE, V_INV,
                      contract_hash)
from policies import SW_WIN

OUT = os.path.join(ROOT, "rtl", "decision", "dec_pkg.sv")


def edges_fn(name, e):
    lines = [f"  // bin = number of edges <= code ({len(e)} edges)",
             f"  function automatic logic [4:0] bin_{name}(input logic signed [15:0] code);",
             "    logic [4:0] b;", "    b = 5'd0;"]
    for x in e:
        lines.append(f"    if (code >= 16'sd{x}) b = b + 5'd1;" if x >= 0 else
                     f"    if (code >= -16'sd{-x}) b = b + 5'd1;")
    lines += ["    return b;", "  endfunction"]
    return lines


def main():
    L = ["// GENERATED by sw/decision/gen_rtl_pkg.py from sw/decision/spec/contract_v0.json -- do not edit",
         f"// contract sha256 {contract_hash()}",
         "package dec_pkg;",
         f"  localparam logic [5:0] ACT_BASE = 6'd0, MODE_BASE = 6'd{MODE_BASE}, BOS = 6'd{BOS};",
         f"  localparam logic [5:0] V_BASE = 6'd{V_BASE}, V_INV = 6'd{V_INV}, I_BASE = 6'd{I_BASE}, I_INV = 6'd{I_INV};",
         f"  localparam logic [5:0] T_BASE = 6'd{T_BASE}, T_INV = 6'd{T_INV};",
         "  // actions (severity order) and modes"]
    L += [f"  localparam logic [1:0] A_{a} = 2'd{i};" for i, a in enumerate(ACTIONS)]
    L += [f"  localparam logic [1:0] M_{m} = 2'd{i};" for i, m in enumerate(MODES)]
    L += ["  // guard limits on raw codes (mV, mA, 0.1 C)",
          f"  localparam int LIM_V = {LIM_V}, LIM_I = {LIM_I}, LIM_T = {LIM_T};",
          f"  localparam int INV_PERSIST = {INV_PERSIST}, INV_SAT = 7;",
          "  localparam logic [1:0] GC_NONE = 2'd0, GC_RESUME = 2'd1, GC_FORCE_SAFE = 2'd2;",
          "  localparam logic [2:0] R_OK = 3'd0, R_FORCE = 3'd1, R_LIM_VT = 3'd2, R_LIM_I = 3'd3,",
          "                         R_RESUME = 3'd4, R_TIMEOUT = 3'd5, R_INVALID = 3'd6, R_DENY = 3'd7;",
          "  // rule thresholds on bins",
          f"  localparam int RULE_V_SAFE = {RULE_V_SAFE}, RULE_V_RESTR = {RULE_V_RESTR}, RULE_T_SAFE = {RULE_T_SAFE}, RULE_I_OC = {RULE_I_OC};",
          f"  localparam int SW_WIN = {SW_WIN};"]
    for ch in ("V", "I", "T"):
        L += edges_fn(ch.lower(), [int(x) for x in EDGES[ch]])
    L += ["  // transition table: replacement action for (mode, proposal); allow -> proposal",
          "  function automatic logic [1:0] tt(input logic [1:0] mode, input logic [1:0] a);",
          "    logic [1:0] r;", "    r = a;", "    case ({mode, a})"]
    for (mi, ai), rep in sorted(TT.items()):
        if rep is not None:
            L.append(f"      4'b{mi:02b}{ai:02b}: r = 2'd{rep};    // {MODES[mi]} x {ACTIONS[ai]} -> {ACTIONS[rep]}")
    L += ["      default: r = a;", "    endcase", "    return r;", "  endfunction",
          "  function automatic logic [1:0] mode_after(input logic [1:0] a, input logic [1:0] mode);",
          "    case (a)", "      A_NORMAL:      return M_NORMAL;", "      A_KISITLI_MOD: return M_KISITLI;",
          "      A_GUVENLI_MOD: return M_GUVENLI;", "      default:       return mode;", "    endcase",
          "  endfunction", "endpackage", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print(OUT)


if __name__ == "__main__":
    main()
