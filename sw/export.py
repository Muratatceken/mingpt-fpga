"""
Step 4: export everything the RTL needs.

  mem/weights.mem  INT8 weights, P lanes per word        (see docs/02_mimari.md, memory map)
  mem/params.mem   per output channel {bias32, m0_16, 8'b0, sh8}
  mem/wte.mem      token embedding, INT16 (scale 2^-FR)
  mem/wpe.mem      position embedding, INT16
  mem/gelu.mem     per-layer 256-entry GELU LUT, address {layer, h[7:0]}
  mem/exp.mem      256-entry 2^(-k/256) LUT, UQ1.15
  mem/tv.txt       golden vectors: every decode step of every test sequence
  mem/trace.txt    residual after every sub-layer (sequence 0), for debugging
  rtl/gpt_pkg.sv         generated SystemVerilog package with all constants
"""
import argparse
import os

from config import MEM_DIR, ROOT, SORT_LENGTH, all_sort_inputs
from intmodel import IntGPT, load_qparams


def hexw(v, bits):
    return format(v & ((1 << bits) - 1), "0{}x".format(bits // 4))


def linears(q):
    """All linear layers in ROM order."""
    out = []
    for l, ql in enumerate(q["layers"]):
        out += [(f"l{l}.attn", ql["attn"]), (f"l{l}.proj", ql["proj"]),
                (f"l{l}.fc", ql["fc"]), (f"l{l}.mproj", ql["mproj"])]
    out.append(("head", q["head"]))
    return out


def write_lines(name, lines):
    with open(os.path.join(MEM_DIR, name), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mem-path", default="mem",
                    help="mem/ directory as seen by the simulator (default: relative to the repo root)")
    args = ap.parse_args()
    mem_path = args.mem_path.replace(os.sep, "/")

    q = load_qparams()
    cfg = q["cfg"]
    C, H, L, V, T, P = (cfg["n_embd"], cfg["n_head"], cfg["n_layer"], cfg["vocab"],
                        cfg["block"], q["P"])
    os.makedirs(MEM_DIR, exist_ok=True)

    # ---- weight ROM: for each linear, for each block of P outputs, for each input i ----
    w_lines, p_lines, offs = [], [], {}
    for name, lin in linears(q):
        W = lin["W"]
        n_out, n_in = W.shape
        assert n_out % P == 0
        offs[name] = (len(w_lines), len(p_lines))
        for ob in range(n_out // P):
            for i in range(n_in):
                word = 0
                for p in range(P):
                    word |= (int(W[ob * P + p, i]) & 0xFF) << (8 * p)
                w_lines.append(hexw(word, 8 * P))
        for o in range(n_out):
            word = ((int(lin["b"][o]) & 0xFFFFFFFF) << 32) | (int(lin["m0"][o]) << 16) | int(lin["sh"][o])
            p_lines.append(hexw(word, 64))
    write_lines("weights.mem", w_lines)
    write_lines("params.mem", p_lines)
    write_lines("wte.mem", [hexw(int(v), 16) for v in q["wte"].flatten()])
    write_lines("wpe.mem", [hexw(int(v), 16) for v in q["wpe"].flatten()])
    gl = []
    for ql in q["layers"]:
        lut = ql["GELU_LUT"]
        gl += [hexw(int(lut[((a ^ 0x80) & 0xFF)]), 8) for a in range(256)]  # address = h[7:0]
    write_lines("gelu.mem", gl)
    write_lines("exp.mem", [hexw(int(v), 16) for v in q["EXP_LUT"]])

    # ---- address map sanity: layer-regular layout assumed by the RTL ----
    w_layer = offs["l1.attn"][0] - offs["l0.attn"][0] if L > 1 else offs["head"][0]
    p_layer = offs["l1.attn"][1] - offs["l0.attn"][1] if L > 1 else offs["head"][1]
    for l in range(L):
        for k in ("attn", "proj", "fc", "mproj"):
            assert offs[f"l{l}.{k}"][0] == l * w_layer + offs[f"l0.{k}"][0]
            assert offs[f"l{l}.{k}"][1] == l * p_layer + offs[f"l0.{k}"][1]

    # ---- RTL datapath width assumptions (see rtl/layernorm.sv, rtl/attention.sv) ----
    assert q["LN_K"] < 2 ** 47 and q["LN_P"] - q["ZF"] >= 1
    assert all(ql["FEXP"] < 64 for ql in q["layers"])

    # ---- SystemVerilog package ----
    def arr(vals, bits):
        return "{" + ", ".join(f"{bits}'d{v}" for v in reversed(vals)) + "}"

    pkg = f"""// ---------------------------------------------------------------------------
// gpt_pkg.sv -- GENERATED by sw/export.py, do not edit by hand.
// Model: minGPT gpt-nano trained on the sort task, INT8/INT16 fixed point.
// ---------------------------------------------------------------------------
package gpt_pkg;
  // location of the .mem files ($readmemh), relative to the simulator's working directory.
  // Local simulation runs from the repo root; the Vivado scripts compile a copy with an absolute path.
  localparam string MEM_PATH = "{mem_path}";

  // model dimensions
  localparam int N_LAYER   = {L};
  localparam int N_HEAD    = {H};
  localparam int N_EMBD    = {C};
  localparam int HEAD_DIM  = {C // H};
  localparam int N_FF      = {4 * C};
  localparam int N_VOCAB   = {V};
  localparam int VOCAB_PAD = {q['head']['W'].shape[0]};
  localparam int BLOCK     = {T};
  localparam int SORT_LEN  = {SORT_LENGTH};      // prompt length of the sort task (self-test)

  // datapath
  localparam int P         = {P};      // MAC lanes in the GEMV engine
  localparam int FR        = {q['FR']};     // residual stream: INT16, scale 2^-FR
  localparam int ZF        = {q['ZF']};      // LayerNorm output: INT8, scale 2^-ZF

  // LayerNorm constants
  localparam int          LN_P = {q['LN_P']};
  localparam logic [63:0] LN_E = 64'd{q['LN_E']};   // round(eps * N^3 / s_r^2)
  localparam logic [63:0] LN_K = 64'd{q['LN_K']};   // round(sqrt(N) * 2^LN_P)

  // softmax constants: exp(x) = 2^(-(delta * CEXP) >> FEXP)
  localparam int ATT_RS = {q['ATT_RS']};
  localparam logic [N_LAYER-1:0][15:0] CEXP = {arr([ql['CEXP'] for ql in q['layers']], 16)};
  localparam logic [N_LAYER-1:0][7:0]  FEXP = {arr([ql['FEXP'] for ql in q['layers']], 8)};

  // weight ROM (P*8-bit words) and parameter ROM (64-bit words) address map
  localparam int W_DEPTH     = {len(w_lines)};
  localparam int W_PER_LAYER = {w_layer};
  localparam int W_OFF_ATTN  = {offs['l0.attn'][0]};
  localparam int W_OFF_PROJ  = {offs['l0.proj'][0]};
  localparam int W_OFF_FC    = {offs['l0.fc'][0]};
  localparam int W_OFF_MPROJ = {offs['l0.mproj'][0]};
  localparam int W_OFF_HEAD  = {offs['head'][0]};
  localparam int PRM_DEPTH     = {len(p_lines)};
  localparam int PRM_PER_LAYER = {p_layer};
  localparam int PRM_OFF_ATTN  = {offs['l0.attn'][1]};
  localparam int PRM_OFF_PROJ  = {offs['l0.proj'][1]};
  localparam int PRM_OFF_FC    = {offs['l0.fc'][1]};
  localparam int PRM_OFF_MPROJ = {offs['l0.mproj'][1]};
  localparam int PRM_OFF_HEAD  = {offs['head'][1]};

  // derived widths
  localparam int W_AW     = $clog2(W_DEPTH);
  localparam int PRM_AW   = $clog2(PRM_DEPTH);
  localparam int LAYER_W  = (N_LAYER > 1) ? $clog2(N_LAYER) : 1;
  localparam int HEAD_W   = (N_HEAD > 1) ? $clog2(N_HEAD) : 1;
  localparam int POS_W    = (BLOCK > 1) ? $clog2(BLOCK) : 1;
  localparam int TOK_W    = (N_VOCAB > 1) ? $clog2(N_VOCAB) : 1;
  localparam int EMB_AW   = $clog2(N_EMBD);
  localparam int DIM_W    = $clog2(((N_FF > VOCAB_PAD) ? N_FF : VOCAB_PAD) + 1);
  localparam int KV_DEPTH = N_LAYER * BLOCK * N_EMBD;
  localparam int KV_AW    = $clog2(KV_DEPTH);
endpackage
"""
    with open(os.path.join(ROOT, "rtl", "gpt_pkg.sv"), "w") as fh:
        fh.write(pkg)

    # ---- golden vectors: all 729 inputs, every decode step ----
    inputs = all_sort_inputs()
    n_steps = 2 * SORT_LENGTH - 1
    tv = [f"{len(inputs)} {SORT_LENGTH} {n_steps}"]
    for prompt in inputs:
        gen, steps = IntGPT(q).generate(prompt, SORT_LENGTH)
        assert len(steps) == n_steps
        for s in steps:
            tv.append(" ".join(map(str, [s["t"], s["tok_in"], s["tok_out"]] + s["logits"] + s["res"])))
    write_lines("tv.txt", tv)

    # ---- per-sub-layer residual trace of sequence 0 ----
    m, tr_lines, seq = IntGPT(q), [], list(inputs[0])
    for t in range(n_steps):
        tr = []
        nxt, _, _ = m.step(seq[t], t, trace=tr)
        if t >= SORT_LENGTH - 1:
            seq.append(nxt)
        for kind, l, res in tr:
            tr_lines.append(" ".join(map(str, [t, l, 0 if kind == "attn" else 1] + res)))
    write_lines("trace.txt", tr_lines)

    print(f"weights.mem: {len(w_lines)} x {8 * P} bit ({len(w_lines) * P} bytes)")
    print(f"params.mem : {len(p_lines)} x 64 bit")
    print(f"tv.txt     : {len(inputs)} sequences x {n_steps} steps")
    print(f"wrote {MEM_DIR} and rtl/gpt_pkg.sv")


if __name__ == "__main__":
    main()
