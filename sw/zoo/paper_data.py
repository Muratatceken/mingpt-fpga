"""
Numbers, tables and plot data of the paper (paper/data/). Every number in the paper comes from here.
  python3 paper_data.py
Reads model/zoo/: runs/<tag>/*.json (training), pipeline.json (INT8 + RTL per run), hw_metrics.json (Yosys),
dse.json, fuzz.json, quant_study.json, int_metrics.json, and -- once measured -- vivado_sweep.jsonl,
board_results.json, power.json, ../../board/pynq_z2/overlay/overlay.json.
Missing measurements appear as a visible \\tbd{} in the PDF, never as invented numbers.
"""
import glob
import json
import math
import os
import statistics as st

from data import ROOT

MZ = os.path.join(ROOT, "model", "zoo")
OUT = os.path.join(ROOT, "paper", "data")
FAMILY = ["bigram", "mlp", "rnn", "gru", "bow", "gpt2", "microgpt", "llama", "nanochat"]
LADDER = ["lad0_gpt2", "lad1_rms", "lad2_rope", "lad3_swiglu", "lad4_gqa", "lad5_llama", "lad6_relu2", "lad7_qknorm"]
LABEL = dict(bigram="Bigram", mlp="MLP", rnn="RNN", gru="GRU", bow="BoW", gpt2="GPT-2", microgpt="microgpt",
             llama="Llama~2", nanochat="nanochat", lad0_gpt2="L0 GPT-2", lad1_rms="L1 +RMSNorm",
             lad2_rope="L2 +RoPE", lad3_swiglu="L3 +SwiGLU", lad4_gqa="L4 +GQA", lad5_llama="L5 Llama~2",
             lad6_relu2="L6 ReLU$^2$", lad7_qknorm="L7 +QK-norm", stories260k="stories260K (pretrained)")
TBD = r"\tbd{}"


def js(name, default=None):
    p = os.path.join(MZ, name)
    return json.load(open(p)) if os.path.exists(p) else default


def jsonl(path):
    if not os.path.exists(path):
        return []
    return [json.loads(l) for l in open(path) if l.strip()]


def num(v, d=0):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return TBD
    return f"{v:,.{d}f}".replace(",", "{,}")


def pm(xs, d=3):
    if not xs:
        return TBD
    if len(xs) == 1:
        return num(xs[0], d)
    return f"{num(st.mean(xs), d)}$\\pm${num(st.stdev(xs), d)}"


def runs(tag):
    """per architecture: best learning rate (validation, seed 0) and the test results at that rate"""
    rs = [json.load(open(f)) for f in glob.glob(os.path.join(MZ, "runs", tag, "*.json"))]
    out = {}
    for arch in sorted({r["arch"] for r in rs}):
        a = [r for r in rs if r["arch"] == arch]
        s0 = [r for r in a if r["seed"] == 0]
        best = min(s0, key=lambda r: r["val_loss"])["lr"] if s0 else a[0]["lr"]
        sel = [r for r in a if r["lr"] == best]
        out[arch] = dict(lr=best, test=[r["test_loss"] for r in sel], val=[r["val_loss"] for r in sel],
                         params=sel[0]["params"], seeds=len(sel), runs=sel,
                         lr_sweep={f"{r['lr']:g}": r["val_loss"] for r in s0})
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    mac = {}
    pipe = js("pipeline.json", {})
    fuzz = js("fuzz.json", {})
    hw = js("hw_metrics.json", {})

    # ---- verification
    vlog = sum(p.get("rtl_logits", 0) for p in pipe.values())
    mac["zooVerifRuns"] = num(sum(1 for p in pipe.values() if p.get("rtl_errors") == 0)) if pipe else TBD
    mac["zooVerifiedLogits"] = num(vlog) if vlog else TBD
    fc = fuzz.get("cases", [])
    mac["zooFuzzCases"] = num(sum(c["status"] == "pass" for c in fc)) if fc else TBD
    mac["zooFuzzLogits"] = num(sum(c.get("logits", 0) for c in fc)) if fc else TBD
    mac["zooArithCases"] = num(36421426)          # tb/tb_zarith.sv (deterministic test set)
    board = js("board_results.json")
    if board:
        errs = sum(m.get("errors", 0) for m in board["models"].values())
        mac["zooBoardVerif"] = f"{len(board['models'])} models, {errs} mismatches"
    else:
        mac["zooBoardVerif"] = TBD
    mac["zooIrErr"] = "$10^{-4}$"
    mac["zooRepoLink"] = r"\url{https://github.com/Muratatceken/mingpt-fpga}"
    mac["zooBudgetTol"] = r"3\%"

    # ---- training protocol
    n50 = runs("names50k")
    seeds = sorted({r["seeds"] for r in n50.values()}) if n50 else []
    mac["zooNamesSeeds"] = str(max(seeds)) if seeds else TBD
    sto = runs("stories260k")
    if sto:
        r0 = next(iter(sto.values()))["runs"][0]
        mac["zooStoriesSteps"] = num(r0["steps"])
        mac["zooStoriesTokensM"] = num(r0["steps"] * r0["batch"] * 256 / 1e6)
    else:
        mac["zooStoriesSteps"] = mac["zooStoriesTokensM"] = TBD
    mac["zooAbstractFinding"] = ""                 # written once the results are final

    with open(os.path.join(OUT, "numbers.tex"), "w") as fh:
        fh.write("% GENERATED by sw/zoo/paper_data.py -- do not edit\n")
        fh.write("\\providecommand{\\tbd}{\\textcolor{red}{\\textbf{TBD}}}\n")
        for k, v in sorted(mac.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    # ---- table: quality and cost per architecture (names 50k, stories)
    rows = []
    for a in FAMILY:
        r, p = n50.get(a), pipe.get(f"names50k/{a}")
        h = hw.get(a, {})
        rows.append(" & ".join([LABEL[a], num(r["params"]) if r else TBD, pm(r["test"]) if r else TBD,
                                num(p["int_delta"], 4) if p else TBD, num(p["cycles"]) if p else
                                num(h.get("cycles_avg")), num(h.get("yosys_spec", {}).get("lut")),
                                num(h.get("yosys_spec", {}).get("dsp"))]) + r" \\")
    open(os.path.join(OUT, "tab_family.tex"), "w").write("\n".join(rows) + "\n")
    print("paper data written to", OUT)


if __name__ == "__main__":
    main()
