"""Gelişim raporunun sayıları ve tabloları: model/zoo/*.json ve git log'dan üretilir (elle sayı yazılmaz).
   python3 veri.py      -> data/*.tex   (gelisim_raporu.tex bunları \\input eder)
Eksik bir sonuç (ör. henüz bitmemiş bir P&R koşusu) tabloda "sürüyor" olarak görünür; betik yeniden
çalıştırılınca tablo kendiliğinden tamamlanır."""
import glob
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ZOO = os.path.join(ROOT, "model", "zoo")
OUT = os.path.join(HERE, "data")
os.makedirs(OUT, exist_ok=True)

NAMES = ["bigram", "mlp", "rnn", "gru", "bow", "gpt2", "microgpt", "llama", "nanochat"]
STORIES = ["stories260k", "ts_gpt2", "ts_gru", "ts_llama", "ts_microgpt", "ts_nanochat"]
LOWBIT = ["gpt2-bin", "mlp-lb25p1", "stories260k-bin"]
BOARD = NAMES + STORIES + LOWBIT
METHODS = ["int8", "int4", "tern", "bin", "lb50p2", "lb25p2", "lb25p1", "lb12p2"]
PENDING = r"\textit{\color{muted}sürüyor}"


def js(name):
    p = os.path.join(ZOO, name)
    return json.load(open(p)) if os.path.exists(p) else {}


def num(v, d=0):
    """Türkçe sayı: binlik ayırıcı ince boşluk, ondalık virgül."""
    if v is None:
        return "–"
    s = f"{v:,.{d}f}".replace(",", "X").replace(".", "{,}").replace("X", r"\,")
    return s.replace("-", "$-$")


def tex(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"),
                 ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")]:
        s = s.replace(a, b)
    return s


def cid(m):
    """pgfplots symbolic coordinate: letters and digits only"""
    return m.replace("_", "").replace("-", "")


def mname(m):
    return r"\code{" + tex(m) + "}"


def write(fn, lines):
    open(os.path.join(OUT, fn), "w").write("% GENERATED by report/gelisim/veri.py\n" + "\n".join(lines) + "\n")


macros = []


def mac(name, val):
    macros.append(r"\newcommand{\g" + name + "}{" + val + "}")


# ------------------------------------------------------------------ git geçmişi
log = subprocess.run(["git", "-C", ROOT, "log", "--reverse", "--format=%ad\t%h\t%s", "--date=format:%d.%m %H:%M"],
                     capture_output=True, text=True).stdout.strip().splitlines()
rows = []
for line in log:
    d, h, s = line.split("\t", 2)
    rows.append(rf"{d} & \code{{{h}}} & {tex(s)} \\")
write("commitler.tex", rows)
days = subprocess.run(["git", "-C", ROOT, "log", "--format=%ad", "--date=short"],
                      capture_output=True, text=True).stdout.split()
mac("Commits", str(len(log)))
mac("CommitDays", str(len(set(days))))

# ------------------------------------------------------------------ 13 Ekim: aile (PYNQ dönemi motoru)
hw, im, met = js("hw_metrics.json"), js("int_metrics.json"), js("metrics.json")
rows = []
for m in NAMES + ["stories260k"]:
    h, i = hw.get(m, {}), im.get(m, {})
    p = met.get(m, {}).get("params")
    cyc = h.get("cycles_avg")
    if m == "stories260k":
        cyc_s = f"{num(h.get('cycles_min'))} … {num(h.get('cycles_max'))}"
    else:
        cyc_s = num(cyc)
    ps = num(p) if p else r"260\,K"
    rows.append(rf"{mname(m)} & {ps} & {num(i.get('float_nll'), 3)} & {num(i.get('int_nll'), 3)} & "
                rf"{num(i.get('delta'), 4)} & {cyc_s} \\")
write("aile.tex", rows)

# ------------------------------------------------------------------ kart (Nexys) sonuçları
nx = js("nexys.json")
rows, cyc_coords = [], []
npass = 0
for m in BOARD:
    r = nx.get(m, {})
    data = "names" if m in NAMES or m in ("gpt2-bin", "mlp-lb25p1") else "TinyStories"
    w = {"gpt2-bin": "binary", "mlp-lb25p1": "LittleBit", "stories260k-bin": "binary"}.get(m, "INT8")
    cpt = r.get("cycles_per_token")
    pn = r.get("pnr", {})
    clk = pn.get("clock_mhz") if pn.get("met") else None
    tps = num(clk * 1e6 / cpt) if (clk and cpt) else PENDING
    ok = r"\textcolor{good}{\textbf{PASS}}" if r.get("sim_pass") else "–"
    npass += bool(r.get("sim_pass"))
    rows.append(rf"{mname(m)} & {data} & {w} & {num(cpt)} & {num(r.get('tokens_per_s_50mhz'))} & "
                rf"{(str(clk) + ' MHz') if clk else PENDING} & {tps} & {ok} \\")
    if cpt:
        cyc_coords.append((m, cpt))
write("kart.tex", rows)
mac("BoardModels", str(len(BOARD)))
mac("BoardPass", str(npass))
write("cyc_plot.tex", [
    r"\begin{tikzpicture}",
    r"\begin{axis}[width=\linewidth, height=6.2cm, ybar, bar width=7pt, ymode=log, log origin=infty,",
    r"  ymin=80, ymax=120000, ylabel={cycle / token}, xtick=data, xticklabel style={rotate=60, anchor=east, font=\sffamily\scriptsize},",
    r"  symbolic x coords={" + ",".join(cid(m) for m, _ in cyc_coords) + "},",
    r"  xticklabels={" + ",".join("{" + tex(m) + "}" for m, _ in cyc_coords) + "},",
    r"  ymajorgrids, enlarge x limits=0.03, axis x line*=bottom, axis y line*=left]",
    r"\addplot[fill=accent!75, draw=none] coordinates {" + " ".join(f"({cid(m)},{c:.0f})" for m, c in cyc_coords) + "};",
    r"\end{axis}",
    r"\end{tikzpicture}",
])

# ------------------------------------------------------------------ yerleşim/yönlendirme (nextpnr) sonuçları
rows, fm = [], []
done = met_n = 0
for m in ["bigram"] + [x for x in BOARD if x != "bigram"]:
    r = nx.get(m, {})
    pn = r.get("pnr")
    if not pn:
        note = r.get("pnr_note")
        cell = (rf"\textcolor{{warm}}{{yerleşim takıldı}}: {num(note['ramb18'])} RAMB18 + {num(note['ramb36'])} RAMB36 "
                rf"$\approx$ {num(note['bram_sites'], 1)}/135 BRAM yeri" if note else PENDING)
        rows.append(rf"{mname(m)} & \multicolumn{{8}}{{l}}{{{cell}}} \\")
        continue
    done += 1
    met_n += bool(pn["met"])
    u = pn.get("utilization", {})
    used = lambda k: int(u[k].split("/")[0]) if k in u else 0
    bram = used("RAMB36E1_RAMB36E1") + used("RAMB18E1_RAMB18E1") / 2
    f50 = pn.get("tried_fmax_mhz", {}).get("50")
    clk, f = pn["clock_mhz"], pn["fmax_mhz"]
    pay = (f / clk - 1) * 100
    st = r"\textcolor{good}{tuttu}" if pn["met"] else r"\textcolor{warm}{tutmadı}"
    rows.append(rf"{mname(m)} & {num(f50, 1)} & {clk} & {num(f, 1)} & {num(pay, 0)}\,\% & {st} & "
                rf"{num(used('SLICE_LUTX'))} & {num(used('SLICE_FFX'))} & {num(bram, 1)} \\")
    fm.append((m, f50, f))
write("pnr.tex", rows)
st = nx.get("stories260k", {})
if st.get("pnr"):
    mac("StoriesLutx", num(int(st["pnr"]["utilization"]["SLICE_LUTX"].split("/")[0])))
mac("StoriesYosysLut", num(st.get("yosys", {}).get("lut")))
mac("StoriesYosysDsp", num(st.get("yosys", {}).get("dsp")))
mac("PnrDone", str(done))
mac("PnrMet", str(met_n))
mac("PnrTotal", str(len(BOARD)))
if fm:
    lo = min(min(a for _, a, _ in fm if a), min(b for _, _, b in fm))
    hi = max(max(a for _, a, _ in fm if a), max(b for _, _, b in fm))
    mac("PnrFmaxMin", num(lo, 1))
    mac("PnrFmaxMax", num(hi, 1))
write("fmax_plot.tex", [
    r"\begin{tikzpicture}",
    r"\begin{axis}[width=\linewidth, height=6.4cm, ybar=1pt, bar width=5pt, ymin=0, ymax=80,",
    r"  ylabel={Fmax (MHz)}, xtick=data, xticklabel style={rotate=60, anchor=east, font=\sffamily\scriptsize},",
    r"  symbolic x coords={" + ",".join(cid(m) for m, _, _ in fm) + "},",
    r"  xticklabels={" + ",".join("{" + tex(m) + "}" for m, _, _ in fm) + "},",
    r"  ymajorgrids, enlarge x limits=0.04, axis x line*=bottom, axis y line*=left,",
    r"  legend style={at={(0.99,0.98)}, anchor=north east, legend columns=2}]",
    r"\addplot[fill=rule, draw=none] coordinates {" + " ".join(f"({cid(m)},{a:.2f})" for m, a, _ in fm if a) + "};",
    r"\addplot[fill=accent, draw=none] coordinates {" + " ".join(f"({cid(m)},{b:.2f})" for m, _, b in fm) + "};",
    r"\legend{50 MHz hedefiyle, son saat hedefiyle}",
    r"\draw[warm, dashed, line width=0.9pt] ({rel axis cs:0,0}|-{axis cs:" + cid(fm[0][0]) + r",50}) -- ({rel axis cs:1,0}|-{axis cs:" + cid(fm[0][0]) + r",50}) node[pos=0.02, above, anchor=south west, font=\sffamily\scriptsize, text=warm] {50 MHz};",
    r"\draw[good, dashed, line width=0.9pt] ({rel axis cs:0,0}|-{axis cs:" + cid(fm[0][0]) + r",25}) -- ({rel axis cs:1,0}|-{axis cs:" + cid(fm[0][0]) + r",25}) node[pos=0.02, below, anchor=north west, font=\sffamily\scriptsize, text=good] {25 MHz};",
    r"\end{axis}",
    r"\end{tikzpicture}",
] if fm else [r"\textit{Henüz sonuç yok.}"])

# ------------------------------------------------------------------ düşük bit (QAT) taraması
rows = []
scatter = {}
for m in ["bow", "gpt2", "gru", "llama", "microgpt", "mlp", "nanochat", "rnn"]:
    cells = []
    fl = None
    for meth in METHODS:
        p = os.path.join(ZOO, "lowbit", m, meth + ".json")
        if not os.path.exists(p):
            cells.append("–")
            continue
        d = json.load(open(p))
        fl = d.get("float_nll", fl)
        cells.append(rf"{num(d['qat_nll'], 3)} \tiny({num(d['bpw'], 2)})")
        scatter.setdefault(m, []).append((meth, d["bpw"], d["qat_nll"]))
    rows.append(rf"{mname(m)} & {num(fl, 3)} & " + " & ".join(cells) + r" \\")
write("lowbit_names.tex", rows)
rows = []
for meth in ["int8", "int4", "bin", "lb25p2", "lb25p1"]:
    p = os.path.join(ZOO, "lowbit", "stories260k", meth + ".json")
    if not os.path.exists(p):
        continue
    d = json.load(open(p))
    qat = rf"{num(d['qat_nll'], 3)} ({num(d['steps'])} adım)" if d.get("steps") else "–"
    rows.append(rf"\code{{{meth}}} & {num(d['bpw'], 2)} & {num(d['ptq_nll'], 3)} & {qat} \\")
    if meth == "int8":
        mac("StoriesFloat", num(d["float_nll"], 3))
write("lowbit_stories.tex", rows)
plot = [r"\begin{tikzpicture}",
        r"\begin{axis}[width=0.92\linewidth, height=6.2cm, xmode=log, xlabel={BPW (weight başına bit)},",
        r"  ylabel={QAT sonrası test kaybı (nat)}, log ticks with fixed point, xtick={0.5,1,2,4,8},",
        r"  ymajorgrids, legend pos=north east, axis x line*=bottom, axis y line*=left]"]
for m, col, mk, anc in [("gpt2", "accent", "*", "south west"), ("mlp", "warm", "square*", "north east")]:
    pts = sorted(scatter.get(m, []), key=lambda t: t[1])
    plot.append(rf"\addplot[only marks, mark={mk}, mark size=2.2pt, color={col}, nodes near coords, point meta=explicit symbolic,"
                r" every node near coord/.style={font=\sffamily\tiny, text=" + col + r", anchor=" + anc + r", inner sep=1.5pt}] coordinates {"
                + " ".join(f"({b:.3f},{l:.4f})[{meth}]" for meth, b, l in pts) + "};")
plot += [r"\legend{{gpt2 (transformer, $C=32$)}, {mlp (makemore MLP, girişi 256)}}", r"\end{axis}", r"\end{tikzpicture}"]
write("lowbit_plot.tex", plot)

# ------------------------------------------------------------------ düşük bitli modeller kartta
