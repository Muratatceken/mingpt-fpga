# ------------------------------------------------------------------ doğrulama: fuzz
bf = js("board_fuzz.json")
runs = sum(v["runs"] for v in bf.values() if isinstance(v, dict) and "runs" in v and "tokens" in v)
toks = sum(v["tokens"] for v in bf.values() if isinstance(v, dict) and "runs" in v and "tokens" in v)
mac("FuzzRuns", num(runs))
mac("FuzzTokens", num(toks))
mac("FuzzModels", str(sum(1 for v in bf.values() if isinstance(v, dict) and "runs" in v and "tokens" in v)))
