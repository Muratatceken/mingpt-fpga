# ------------------------------------------------------------------ P tasarım uzayı
dse = js("dse.json")
rows = []
for m in ["mlp", "gru", "gpt2", "llama", "nanochat", "stories260k"]:
    c = [dse.get(f"{m}_P{p}", {}).get("cycles") for p in (8, 16, 32)]
    g = [dse.get(f"{m}_P{p}", {}).get("gemv") for p in (8, 16, 32)]
    if not c[0]:
        continue
    sp = c[0] / c[2] if c[2] else None
    gsp = g[0] / g[2] if (g[0] and g[2]) else None
    rows.append(rf"{mname(m)} & {num(c[0])} & {num(c[1])} & {num(c[2])} & {num(gsp, 2)}$\times$ & {num(sp, 2)}$\times$ \\")
write("dse.tex", rows)

write("sayilar.tex", macros)
print(f"{len(log)} commit, kart {npass}/{len(BOARD)} PASS, P&R {done}/{len(BOARD)} ({met_n} tuttu), fuzz {runs} koşu / {toks} token")
