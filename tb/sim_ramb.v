  parameter [255:0] INITP_0C = 256'h0;
  parameter [255:0] INITP_0D = 256'h0;
  parameter [255:0] INITP_0E = 256'h0;
  parameter [255:0] INITP_0F = 256'h0;
  parameter [71:0] INIT_A = 72'h0, INIT_B = 72'h0, SRVAL_A = 72'h0, SRVAL_B = 72'h0;
  parameter integer READ_WIDTH_A = 0, READ_WIDTH_B = 0, WRITE_WIDTH_A = 0, WRITE_WIDTH_B = 0;
  parameter integer DOA_REG = 0, DOB_REG = 0;
  parameter RAM_MODE = "TDP", WRITE_MODE_A = "WRITE_FIRST", WRITE_MODE_B = "WRITE_FIRST";
  parameter RDADDR_COLLISION_HWCONFIG = "DELAYED_WRITE", SIM_COLLISION_CHECK = "ALL", SIM_DEVICE = "7SERIES";
  parameter INIT_FILE = "NONE", RSTREG_PRIORITY_A = "RSTREG", RSTREG_PRIORITY_B = "RSTREG";
  parameter RAM_EXTENSION_A = "NONE", RAM_EXTENSION_B = "NONE", EN_ECC_READ = "FALSE", EN_ECC_WRITE = "FALSE";
  parameter [0:0] IS_CLKARDCLK_INVERTED = 1'b0, IS_CLKBWRCLK_INVERTED = 1'b0, IS_ENARDEN_INVERTED = 1'b0,
                  IS_ENBWREN_INVERTED = 1'b0, IS_RSTRAMARSTRAM_INVERTED = 1'b0, IS_RSTRAMB_INVERTED = 1'b0,
                  IS_RSTREGARSTREG_INVERTED = 1'b0, IS_RSTREGB_INVERTED = 1'b0;

  localparam integer NB = 4096;                      // 9-bit lanes
  localparam [32767:0] INIT_ALL = {INIT_7F, INIT_7E, INIT_7D, INIT_7C, INIT_7B, INIT_7A, INIT_79, INIT_78, INIT_77, INIT_76, INIT_75, INIT_74, INIT_73, INIT_72, INIT_71, INIT_70, INIT_6F, INIT_6E, INIT_6D, INIT_6C, INIT_6B, INIT_6A, INIT_69, INIT_68, INIT_67, INIT_66, INIT_65, INIT_64, INIT_63, INIT_62, INIT_61, INIT_60, INIT_5F, INIT_5E, INIT_5D, INIT_5C, INIT_5B, INIT_5A, INIT_59, INIT_58, INIT_57, INIT_56, INIT_55, INIT_54, INIT_53, INIT_52, INIT_51, INIT_50, INIT_4F, INIT_4E, INIT_4D, INIT_4C, INIT_4B, INIT_4A, INIT_49, INIT_48, INIT_47, INIT_46, INIT_45, INIT_44, INIT_43, INIT_42, INIT_41, INIT_40, INIT_3F, INIT_3E, INIT_3D, INIT_3C, INIT_3B, INIT_3A, INIT_39, INIT_38, INIT_37, INIT_36, INIT_35, INIT_34, INIT_33, INIT_32, INIT_31, INIT_30, INIT_2F, INIT_2E, INIT_2D, INIT_2C, INIT_2B, INIT_2A, INIT_29, INIT_28, INIT_27, INIT_26, INIT_25, INIT_24, INIT_23, INIT_22, INIT_21, INIT_20, INIT_1F, INIT_1E, INIT_1D, INIT_1C, INIT_1B, INIT_1A, INIT_19, INIT_18, INIT_17, INIT_16, INIT_15, INIT_14, INIT_13, INIT_12, INIT_11, INIT_10, INIT_0F, INIT_0E, INIT_0D, INIT_0C, INIT_0B, INIT_0A, INIT_09, INIT_08, INIT_07, INIT_06, INIT_05, INIT_04, INIT_03, INIT_02, INIT_01, INIT_00};
  localparam [4095:0] INITP_ALL = {INITP_0F, INITP_0E, INITP_0D, INITP_0C, INITP_0B, INITP_0A, INITP_09, INITP_08, INITP_07, INITP_06, INITP_05, INITP_04, INITP_03, INITP_02, INITP_01, INITP_00};
  localparam SDP = (RAM_MODE == "SDP");
  localparam integer RWA = SDP ? READ_WIDTH_A : READ_WIDTH_A, RWB = SDP ? 0 : READ_WIDTH_B;
  localparam integer WWA = SDP ? 0 : WRITE_WIDTH_A, WWB = WRITE_WIDTH_B;

  assign {CASCADEOUTA, CASCADEOUTB, DBITERR, SBITERR, ECCPARITY, RDADDRECC} = 21'd0;

  reg [7:0] md [0:NB-1];
  reg       mp [0:NB-1];
  integer i;
  initial begin
    for (i = 0; i < NB; i = i + 1) begin
      md[i] = INIT_ALL[8 * i +: 8];
      mp[i] = INITP_ALL[i];
    end
    {DOPBDOP, DOBDO, DOPADOP, DOADO} = 0;
    {DOPADOP, DOADO} = INIT_A[35:0];
    if (!SDP) {DOPBDOP, DOBDO} = INIT_B[35:0];
    if (DOA_REG != 0 || DOB_REG != 0 || RAM_EXTENSION_A != "NONE" || RAM_EXTENSION_B != "NONE" ||
        EN_ECC_READ != "FALSE" || EN_ECC_WRITE != "FALSE" ||
        {IS_CLKARDCLK_INVERTED, IS_CLKBWRCLK_INVERTED, IS_ENARDEN_INVERTED, IS_ENBWREN_INVERTED,
         IS_RSTRAMARSTRAM_INVERTED, IS_RSTRAMB_INVERTED, IS_RSTREGARSTREG_INVERTED, IS_RSTREGB_INVERTED} != 0 ||
        (SDP && !((READ_WIDTH_A == 0 || READ_WIDTH_A == 72) && (WRITE_WIDTH_B == 0 || WRITE_WIDTH_B == 72))))
      $display("ERROR RAMB36E1 %m: configuration not supported by tb/sim_ramb.v");
  end

  // ---- helpers: data width without parity, lanes, word address ----
  function integer dbits(input integer w);              // 9 -> 8, 18 -> 16, 36 -> 32, 72 -> 64
    dbits = (w >= 9) ? w / 9 * 8 : w;
  endfunction
  function integer lg(input integer v);
    integer k;
    begin lg = 0; for (k = 1; k < v; k = k * 2) lg = lg + 1; end
  endfunction
  function integer waddr(input [15:0] a, input integer w);
    waddr = (a & 16'h7fff) >> lg(dbits(w));
  endfunction

  // read W bits of word k -> {parity lanes, data lanes} as {dop, do} packed (do in [63:0], dop in [71:64])
  function [71:0] rd(input integer k, input integer w);
    integer j, b;
    begin
      rd = 72'h0;
      if (w >= 9)
        for (j = 0; j < w / 9; j = j + 1) begin
          rd[8 * j +: 8] = md[k * (w / 9) + j];
          rd[64 + j]     = mp[k * (w / 9) + j];
        end
      else
        for (j = 0; j < w; j = j + 1) begin
          b = k * w + j;
          rd[j] = md[b / 8][b % 8];
        end
    end
  endfunction

  // ---- port A (TDP read/write; SDP: the read port) ----
  reg [71:0] ra, rb, wa_d, wb_d;
  reg [7:0]  wa_e, wb_e;
  integer ka, kb, j, b, jb;                             // (always blocks run without suspending: shared is fine)
  always @(posedge CLKARDCLK) if (ENARDEN) begin
    ka = waddr(ADDRARDADDR, SDP ? READ_WIDTH_A : (RWA > 0 ? RWA : WWA));
    if (RSTRAMARSTRAM) ra = SRVAL_A;
    else ra = (RWA > 0) ? rd(ka, RWA) : 72'h0;
    if (WWA > 0) begin                                  // TDP write on port A
      ka = waddr(ADDRARDADDR, WWA);
      if (WWA >= 9)
        for (j = 0; j < WWA / 9; j = j + 1) if (WEA[j % 4]) begin
          md[ka * (WWA / 9) + j] <= (j < 4) ? DIADI[8 * j +: 8] : 8'h0;
          mp[ka * (WWA / 9) + j] <= DIPADIP[j];
          if (WRITE_MODE_A == "WRITE_FIRST") begin ra[8 * j +: 8] = DIADI[8 * j +: 8]; ra[64 + j] = DIPADIP[j]; end
        end
      else if (WEA[0])
        for (j = 0; j < WWA; j = j + 1) begin
          b = ka * WWA + j;
          md[b / 8][b % 8] <= DIADI[j];
          if (WRITE_MODE_A == "WRITE_FIRST") ra[j] = DIADI[j];
        end
    end
    if (!(WWA > 0 && |WEA && WRITE_MODE_A == "NO_CHANGE")) begin
      if (SDP) begin
        DOADO   <= ra[31:0];
        DOBDO   <= ra[63:32];
        DOPADOP <= ra[64 +: 4];
        DOPBDOP <= ra[64 + 4 +: 4];
      end else if (RSTRAMARSTRAM) {DOPADOP, DOADO} <= SRVAL_A;
      else begin
        DOADO   <= ra[31:0];
        DOPADOP <= ra[64 +: 4];
      end
    end
  end

  // ---- port B (TDP read/write; SDP: the write port) ----
  always @(posedge CLKBWRCLK) if (ENBWREN) begin
    if (SDP) begin
      if (WWB > 0) begin
        kb = waddr(ADDRBWRADDR, WWB);
        wb_d = 72'h0;
        wb_d[63:0]  = {DIBDI, DIADI};
        wb_d[64 +: 8] = {DIPBDIP, DIPADIP};
        for (jb = 0; jb < WWB / 9; jb = jb + 1) if (WEBWE[jb]) begin
          md[kb * (WWB / 9) + jb] <= wb_d[8 * jb +: 8];
          mp[kb * (WWB / 9) + jb] <= wb_d[64 + jb];
        end
      end
    end else begin
      kb = waddr(ADDRBWRADDR, RWB > 0 ? RWB : WWB);
      rb = (RWB > 0) ? rd(kb, RWB) : 72'h0;
      if (WWB > 0) begin
        kb = waddr(ADDRBWRADDR, WWB);
        if (WWB >= 9)
          for (j = 0; j < WWB / 9; j = j + 1) if (WEBWE[j % 8]) begin
            md[kb * (WWB / 9) + j] <= DIBDI[8 * j +: 8];
            mp[kb * (WWB / 9) + j] <= DIPBDIP[j];
            if (WRITE_MODE_B == "WRITE_FIRST") begin rb[8 * j +: 8] = DIBDI[8 * j +: 8]; rb[64 + j] = DIPBDIP[j]; end
          end
        else if (WEBWE[0])
          for (j = 0; j < WWB; j = j + 1) begin
            b = kb * WWB + j;
            md[b / 8][b % 8] <= DIBDI[j];
            if (WRITE_MODE_B == "WRITE_FIRST") rb[j] = DIBDI[j];
          end
      end
      if (!(WWB > 0 && |WEBWE && WRITE_MODE_B == "NO_CHANGE")) begin
        if (RSTRAMB) {DOPBDOP, DOBDO} <= SRVAL_B;
        else begin
          DOBDO   <= rb[31:0];
          DOPBDOP <= rb[64 +: 4];
        end
      end
    end
  end
endmodule
