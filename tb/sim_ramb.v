// All reads of a clock edge see the memory before the writes of that edge (READ_FIRST for the writing port;
// WRITE_FIRST: the written lanes show the new data; NO_CHANGE: the output keeps its value while writing).
// Supported: DOA_REG = DOB_REG = 0, no cascading, no inverted pins, no ECC; anything else is reported.
