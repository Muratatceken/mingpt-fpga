"""writes tb/sim_ramb.v: behavioural RAMB18E1 / RAMB36E1 for simulating Yosys netlists
    python3 scripts/gen_sim_ramb.py tb/sim_ramb.v"""
import sys

HDR = """// ---------------------------------------------------------------------------
// sim_ramb.v -- behavioural simulation models of the Xilinx 7-series block RAMs RAMB18E1 and RAMB36E1 for
// post-synthesis netlists of Yosys synth_xilinx (scripts/nexys_netlist_sim.sh). The cells_sim.v of the
// installed Yosys declares these cells without behaviour (outputs floating).
// Memory layout as Yosys' memory_libmap writes the INIT parameters (techlibs/xilinx/brams_defs.vh): 9-bit
// lanes, data byte n = INIT bits [8n +: 8], parity bit n = INITP bit n; a port of width W >= 9 reads lanes
// k*W/9 ... k*W/9 + W/9 - 1 of word k (data on DO[8j +: 8], parity on DOP[j]); widths 1, 2, 4 address the data
// bits only. Word address = ADDR[13:log2(W')] (RAMB18) / ADDR[14:log2(W')] (RAMB36), W' = W without parity.
// TDP: ports A and B independent (READ_WIDTH / WRITE_WIDTH per port). SDP (36 / 72 bits): reads on port A
// (DOADO low half, DOBDO high half), writes on port B (DIADI low, DIBDI high, WEBWE per lane).
// All reads of a clock edge see the memory before the writes of that edge (READ_FIRST for the writing port;
// WRITE_FIRST: the written lanes show the new data; NO_CHANGE: the output keeps its value while writing).
// Supported: DOA_REG = DOB_REG = 0, no cascading, no inverted pins, no ECC; anything else is reported.
// Generated by scripts/gen_sim_ramb.py (one parameter per INIT word); do not edit by hand.
// ---------------------------------------------------------------------------
`timescale 1ns / 1ps
"""


def model(name, nb, aw, ninit, ninitp, dw, pw, wea_w, web_w):
    o = []
    o.append(f"""
module {name} (
  input CLKARDCLK, CLKBWRCLK, ENARDEN, ENBWREN, REGCEAREGCE, REGCEB,
  input RSTRAMARSTRAM, RSTRAMB, RSTREGARSTREG, RSTREGB,""")
    if name == "RAMB36E1":
        o.append("  input CASCADEINA, CASCADEINB, INJECTDBITERR, INJECTSBITERR,")
        o.append("  output CASCADEOUTA, CASCADEOUTB, DBITERR, SBITERR, output [7:0] ECCPARITY, output [8:0] RDADDRECC,")
    o.append(f"""  input [{aw - 1}:0] ADDRARDADDR, ADDRBWRADDR,
  input [{dw - 1}:0] DIADI, DIBDI,
  input [{pw - 1}:0] DIPADIP, DIPBDIP,
  input [{wea_w - 1}:0] WEA,
  input [{web_w - 1}:0] WEBWE,
  output reg [{dw - 1}:0] DOADO, DOBDO,
  output reg [{pw - 1}:0] DOPADOP, DOPBDOP
);""")
    for k in range(ninit):
        o.append(f"  parameter [255:0] INIT_{k:02X} = 256'h0;")
    for k in range(ninitp):
        o.append(f"  parameter [255:0] INITP_{k:02X} = 256'h0;")
    o.append(f"""  parameter [71:0] INIT_A = 72'h0, INIT_B = 72'h0, SRVAL_A = 72'h0, SRVAL_B = 72'h0;
  parameter integer READ_WIDTH_A = 0, READ_WIDTH_B = 0, WRITE_WIDTH_A = 0, WRITE_WIDTH_B = 0;
  parameter integer DOA_REG = 0, DOB_REG = 0;
  parameter RAM_MODE = "TDP", WRITE_MODE_A = "WRITE_FIRST", WRITE_MODE_B = "WRITE_FIRST";
  parameter RDADDR_COLLISION_HWCONFIG = "DELAYED_WRITE", SIM_COLLISION_CHECK = "ALL", SIM_DEVICE = "7SERIES";
  parameter INIT_FILE = "NONE", RSTREG_PRIORITY_A = "RSTREG", RSTREG_PRIORITY_B = "RSTREG";
  parameter RAM_EXTENSION_A = "NONE", RAM_EXTENSION_B = "NONE", EN_ECC_READ = "FALSE", EN_ECC_WRITE = "FALSE";
  parameter [0:0] IS_CLKARDCLK_INVERTED = 1'b0, IS_CLKBWRCLK_INVERTED = 1'b0, IS_ENARDEN_INVERTED = 1'b0,
                  IS_ENBWREN_INVERTED = 1'b0, IS_RSTRAMARSTRAM_INVERTED = 1'b0, IS_RSTRAMB_INVERTED = 1'b0,
                  IS_RSTREGARSTREG_INVERTED = 1'b0, IS_RSTREGB_INVERTED = 1'b0;

  localparam integer NB = {nb};                      // 9-bit lanes
  localparam [{256 * ninit - 1}:0] INIT_ALL = {{{", ".join(f"INIT_{k:02X}" for k in reversed(range(ninit)))}}};
  localparam [{256 * ninitp - 1}:0] INITP_ALL = {{{", ".join(f"INITP_{k:02X}" for k in reversed(range(ninitp)))}}};
  localparam SDP = (RAM_MODE == "SDP");
  localparam integer RWA = SDP ? READ_WIDTH_A : READ_WIDTH_A, RWB = SDP ? 0 : READ_WIDTH_B;
  localparam integer WWA = SDP ? 0 : WRITE_WIDTH_A, WWB = WRITE_WIDTH_B;
""")
    if name == "RAMB36E1":
        o.append("  assign {CASCADEOUTA, CASCADEOUTB, DBITERR, SBITERR, ECCPARITY, RDADDRECC} = 21'd0;")
    o.append(f"""
  reg [7:0] md [0:NB-1];
  reg       mp [0:NB-1];
  integer i;
  initial begin
    for (i = 0; i < NB; i = i + 1) begin
      md[i] = INIT_ALL[8 * i +: 8];
      mp[i] = INITP_ALL[i];
    end
    {{DOPBDOP, DOBDO, DOPADOP, DOADO}} = 0;
    {{DOPADOP, DOADO}} = INIT_A[{dw + pw - 1}:0];
    if (!SDP) {{DOPBDOP, DOBDO}} = INIT_B[{dw + pw - 1}:0];
    if (DOA_REG != 0 || DOB_REG != 0 || RAM_EXTENSION_A != "NONE" || RAM_EXTENSION_B != "NONE" ||
        EN_ECC_READ != "FALSE" || EN_ECC_WRITE != "FALSE" ||
        {{IS_CLKARDCLK_INVERTED, IS_CLKBWRCLK_INVERTED, IS_ENARDEN_INVERTED, IS_ENBWREN_INVERTED,
         IS_RSTRAMARSTRAM_INVERTED, IS_RSTRAMB_INVERTED, IS_RSTREGARSTREG_INVERTED, IS_RSTREGB_INVERTED}} != 0 ||
        (SDP && !((READ_WIDTH_A == 0 || READ_WIDTH_A == {2 * (dw + pw)}) && (WRITE_WIDTH_B == 0 || WRITE_WIDTH_B == {2 * (dw + pw)}))))
      $display("ERROR {name} %m: configuration not supported by tb/sim_ramb.v");
  end

  // ---- helpers: data width without parity, lanes, word address ----
  function integer dbits(input integer w);              // 9 -> 8, 18 -> 16, 36 -> 32, 72 -> 64
    dbits = (w >= 9) ? w / 9 * 8 : w;
  endfunction
  function integer lg(input integer v);
    integer k;
    begin lg = 0; for (k = 1; k < v; k = k * 2) lg = lg + 1; end
  endfunction
  function integer waddr(input [{aw - 1}:0] a, input integer w);
    waddr = (a & {aw}'h{(1 << (aw if name == "RAMB18E1" else aw - 1)) - 1:x}) >> lg(dbits(w));
  endfunction

  // read W bits of word k -> {{parity lanes, data lanes}} as {{dop, do}} packed (do in [63:0], dop in [71:64])
  function [71:0] rd(input integer k, input integer w);
    integer j, b;
    begin
      rd = 72'h0;
      if (w >= 9)
        for (j = 0; j < w / 9; j = j + 1) begin
          rd[8 * j +: 8] = md[k * (w / 9) + j];
          rd[64 + j]     = mp[k * (w / 9) + j];
        end
      else
        for (j = 0; j < w; j = j + 1) begin
          b = k * w + j;
          rd[j] = md[b / 8][b % 8];
        end
    end
  endfunction

  // ---- port A (TDP read/write; SDP: the read port) ----
  reg [71:0] ra, rb, wa_d, wb_d;
  reg [7:0]  wa_e, wb_e;
  integer ka, kb, j, b, jb;                             // (always blocks run without suspending: shared is fine)
  always @(posedge CLKARDCLK) if (ENARDEN) begin
    ka = waddr(ADDRARDADDR, SDP ? READ_WIDTH_A : (RWA > 0 ? RWA : WWA));
    if (RSTRAMARSTRAM) ra = SRVAL_A;
    else ra = (RWA > 0) ? rd(ka, RWA) : 72'h0;
    if (WWA > 0) begin                                  // TDP write on port A
      ka = waddr(ADDRARDADDR, WWA);
      if (WWA >= 9)
        for (j = 0; j < WWA / 9; j = j + 1) if (WEA[j % {wea_w}]) begin
          md[ka * (WWA / 9) + j] <= (j < {dw // 8}) ? DIADI[8 * j +: 8] : 8'h0;
          mp[ka * (WWA / 9) + j] <= DIPADIP[j];
          if (WRITE_MODE_A == "WRITE_FIRST") begin ra[8 * j +: 8] = DIADI[8 * j +: 8]; ra[64 + j] = DIPADIP[j]; end
        end
      else if (WEA[0])
        for (j = 0; j < WWA; j = j + 1) begin
          b = ka * WWA + j;
          md[b / 8][b % 8] <= DIADI[j];
          if (WRITE_MODE_A == "WRITE_FIRST") ra[j] = DIADI[j];
        end
    end
    if (!(WWA > 0 && |WEA && WRITE_MODE_A == "NO_CHANGE")) begin
      if (SDP) begin
        DOADO   <= ra[{dw - 1}:0];
        DOBDO   <= ra[{2 * dw - 1}:{dw}];
        DOPADOP <= ra[64 +: {pw}];
        DOPBDOP <= ra[64 + {pw} +: {pw}];
      end else if (RSTRAMARSTRAM) {{DOPADOP, DOADO}} <= SRVAL_A;
      else begin
        DOADO   <= ra[{dw - 1}:0];
        DOPADOP <= ra[64 +: {pw}];
      end
    end
  end

  // ---- port B (TDP read/write; SDP: the write port) ----
  always @(posedge CLKBWRCLK) if (ENBWREN) begin
    if (SDP) begin
      if (WWB > 0) begin
        kb = waddr(ADDRBWRADDR, WWB);
        wb_d = 72'h0;
        wb_d[{2 * dw - 1}:0]  = {{DIBDI, DIADI}};
        wb_d[64 +: {2 * pw}] = {{DIPBDIP, DIPADIP}};
        for (jb = 0; jb < WWB / 9; jb = jb + 1) if (WEBWE[jb]) begin
          md[kb * (WWB / 9) + jb] <= wb_d[8 * jb +: 8];
          mp[kb * (WWB / 9) + jb] <= wb_d[64 + jb];
        end
      end
    end else begin
      kb = waddr(ADDRBWRADDR, RWB > 0 ? RWB : WWB);
      rb = (RWB > 0) ? rd(kb, RWB) : 72'h0;
      if (WWB > 0) begin
        kb = waddr(ADDRBWRADDR, WWB);
        if (WWB >= 9)
          for (j = 0; j < WWB / 9; j = j + 1) if (WEBWE[j % {web_w}]) begin
            md[kb * (WWB / 9) + j] <= DIBDI[8 * j +: 8];
            mp[kb * (WWB / 9) + j] <= DIPBDIP[j];
            if (WRITE_MODE_B == "WRITE_FIRST") begin rb[8 * j +: 8] = DIBDI[8 * j +: 8]; rb[64 + j] = DIPBDIP[j]; end
          end
        else if (WEBWE[0])
          for (j = 0; j < WWB; j = j + 1) begin
            b = kb * WWB + j;
            md[b / 8][b % 8] <= DIBDI[j];
            if (WRITE_MODE_B == "WRITE_FIRST") rb[j] = DIBDI[j];
          end
      end
      if (!(WWB > 0 && |WEBWE && WRITE_MODE_B == "NO_CHANGE")) begin
        if (RSTRAMB) {{DOPBDOP, DOBDO}} <= SRVAL_B;
        else begin
          DOBDO   <= rb[{dw - 1}:0];
          DOPBDOP <= rb[64 +: {pw}];
        end
      end
    end
  end
endmodule
""")
    return "\n".join(o)


out = HDR + model("RAMB18E1", 2048, 14, 64, 8, 16, 2, 2, 4) + model("RAMB36E1", 4096, 16, 128, 16, 32, 4, 4, 8)
open(sys.argv[1], "w").write(out)
